namespace Darkspyre.Inference.Connect.LLM.Tests;

public sealed class LlmResourceMaterializationTests
{
    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task KnownInvalidReferenceRefusesBeforeCredentialRefresh(bool native)
    {
        var auth = new RefreshObserver();
        var connection = Connection() with { Credential = new LlmCredential { OAuth = new() { AccessToken = "expired", RefreshToken = "refresh", ExpiresAtUnixSeconds = 0 } }.Serialize() };
        using var http = new HttpClient(new ResourceDestination());
        await using var service = new LlmProviderService(new Source(connection), [new XaiResponsesLlmClient(http)], [auth]);
        var request = new LlmChatRequest
        {
            ModelId = "grok-4",
            Messages = [new("user", "inspect") { Attachments = [native ? new LlmFileReference(new("..")) : new LlmResourceAttachment(new("workspace", "missing-authority"))] }]
        };
        await Assert.ThrowsAnyAsync<ArgumentException>(() => ReadAsync(service.StreamAsync("selected", request)));
        Assert.Equal(0, auth.Refreshes);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ActualXaiDestinationUploadsSelectedOriginalAndGeneratedBytes(bool facade)
    {
        var resources = new ControlledSessionResources();
        var original = await resources.RegisterAsync("original.txt", "text/plain", "original content");
        var generated = await resources.RegisterAsync("generated.json", "application/json", "{\"actual\":42}");
        using var handler = new ResourceDestination();
        using var http = new HttpClient(handler);
        var client = new XaiResponsesLlmClient(http);
        await using var service = new LlmProviderService(new Source(Connection()), [client]);
        var request = Request(resources);
        var result = await ReadAsync(facade ? service.StreamAsync("selected", request) : client.StreamAsync(Connection(), request));
        Assert.Single(result.OfType<LlmChatCompletionEvent>());
        Assert.Equal<string>(["original.txt", "generated.json"], handler.Uploads.Select(item => item.Name));
        Assert.Equal("original content", Encoding.UTF8.GetString(handler.Uploads[0].Bytes));
        Assert.Equal("{\"actual\":42}", Encoding.UTF8.GetString(handler.Uploads[1].Bytes));
        Assert.Equal<string>(["file-1", "file-2"], FileIds(handler.Prompt!));
        Assert.Equal(1, resources.SelectionReads);
        Assert.Equal(2, resources.OpenedReads);
        Assert.Equal(2, resources.DisposedReads);
        Assert.Equal(new[] { original, generated }, (await resources.GetSelectionAsync()).SelectedResources);
        Assert.Empty(request.Messages[0].Attachments);
        Assert.Same(resources, request.Resources);
        Assert.Equal(0, resources.DisposeCalls);
    }

    [Fact]
    public async Task SurvivingCallerStoreRematerializesBothFilesAfterFirstFacadeRetires()
    {
        var resources = new ControlledSessionResources();
        await resources.RegisterAsync("original.txt", "text/plain", "source text");
        var firstHandler = new ResourceDestination();
        using var firstHttp = new HttpClient(firstHandler);
        var first = new LlmProviderService(new Source(Connection()), [new XaiResponsesLlmClient(firstHttp)]);
        try
        {
            await ReadAsync(first.StreamAsync("provider-a", Request(resources)));
            // The caller commits generated bytes before A retires; B never needs A's native state.
            await resources.RegisterAsync("generated.json", "application/json", "{\"from\":\"caller-tool\"}");
        }
        finally { await first.DisposeAsync(); }
        using var secondHandler = new ResourceDestination();
        using var secondHttp = new HttpClient(secondHandler);
        await using var second = new LlmProviderService(new Source(Connection() with { Version = "v2" }), [new XaiResponsesLlmClient(secondHttp)]);
        await ReadAsync(second.StreamAsync("provider-b", Request(resources)));
        Assert.Equal<string>(["source text", "{\"from\":\"caller-tool\"}"], secondHandler.Uploads.Select(item => Encoding.UTF8.GetString(item.Bytes)));
        Assert.Equal("logical-session", resources.SessionId);
        Assert.Equal(0, resources.DisposeCalls);
        Assert.Equal(resources.OpenedReads, resources.DisposedReads);
    }

    [Fact]
    public async Task ExplicitDuplicateOccurrencesRemainWhileSelectionAddsOnlyAbsentContent()
    {
        var resources = new ControlledSessionResources();
        InferenceResourceReference explicitFile = await resources.RegisterAsync("explicit.txt", "text/plain", "explicit");
        await resources.RegisterAsync("selected.txt", "text/plain", "selected");
        using var handler = new ResourceDestination();
        using var http = new HttpClient(handler);
        var request = Request(resources) with
        {
            Messages = [new("user", "inspect") { Attachments = [new LlmResourceAttachment(explicitFile), new LlmResourceAttachment(explicitFile)] }]
        };
        await ReadAsync(new XaiResponsesLlmClient(http).StreamAsync(Connection(), request));
        string[] ids = FileIds(handler.Prompt!);
        Assert.Equal(3, ids.Length);
        Assert.Equal(ids[0], ids[1]);
        Assert.NotEqual(ids[0], ids[2]);
        Assert.Equal(2, handler.Uploads.Count);
        Assert.Equal(2, request.Messages[0].Attachments.Count);
    }

    internal static LlmConnection Connection() => new()
    {
        Version = "v1",
        Transport = LlmTransport.XaiResponses,
        Endpoint = "https://api.x.ai/v1",
        Credential = new LlmCredential
        {
            OAuth = new() { AccessToken = "access", RefreshToken = "refresh", ExpiresAtUnixSeconds = DateTimeOffset.UtcNow.AddHours(1).ToUnixTimeSeconds() }
        }.Serialize(),
        CapabilityOverrides = new() { SupportsStreaming = false }
    };

    internal static LlmChatRequest Request(IInferenceResourceAccess resources) => new()
    { ModelId = "grok-4", Messages = [new("user", "inspect the selected files")], Resources = resources };

    internal static async Task<List<LlmStreamEvent>> ReadAsync(IAsyncEnumerable<LlmStreamEvent> stream)
    { var events = new List<LlmStreamEvent>(); await foreach (var item in stream) events.Add(item); return events; }

    private static string[] FileIds(string prompt)
    {
        using var document = JsonDocument.Parse(prompt);
        return document.RootElement.GetProperty("input").EnumerateArray()
            .Where(item => item.TryGetProperty("content", out var content) && content.ValueKind == JsonValueKind.Array)
            .SelectMany(item => item.GetProperty("content").EnumerateArray())
            .Where(item => item.GetProperty("type").GetString() == "input_file")
            .Select(item => item.GetProperty("file_id").GetString()!).ToArray();
    }

    internal sealed class Source(LlmConnection connection) : ILlmConnectionSource
    {
        public Task<LlmConnection?> GetConnectionAsync(string id, CancellationToken cancellationToken = default) => Task.FromResult<LlmConnection?>(connection);
        public Task SaveCredentialAsync(string id, string credential, string expectedVersion, CancellationToken cancellationToken = default) => Task.CompletedTask;
    }

    private sealed class RefreshObserver : ILlmAuthenticator
    {
        public LlmTransport Transport => LlmTransport.XaiResponses;
        internal int Refreshes { get; private set; }
        public Task<LlmCredential> EnsureFreshAsync(LlmCredential credential, CancellationToken cancellationToken = default)
        { Refreshes++; return Task.FromResult(credential with { OAuth = new() { AccessToken = "refreshed" } }); }
    }

    internal sealed class ResourceDestination : HttpMessageHandler
    {
        internal List<(string Name, byte[] Bytes)> Uploads { get; } = [];
        internal Queue<string> Responses { get; } = new();
        internal string? Prompt { get; private set; }
        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken token)
        {
            string path = request.RequestUri!.AbsolutePath;
            if (path.EndsWith("/models", StringComparison.Ordinal)) return Json("{\"data\":[]}");
            if (path.EndsWith("/language-models", StringComparison.Ordinal)) return Json("{\"models\":[]}");
            if (path.EndsWith("/files", StringComparison.Ordinal))
            {
                var multipart = Assert.IsType<MultipartFormDataContent>(request.Content);
                HttpContent file = multipart.Single(content => content.Headers.ContentDisposition?.Name?.Trim('"') == "file");
                string name = file.Headers.ContentDisposition!.FileName!.Trim('"');
                byte[] bytes = await file.ReadAsByteArrayAsync(token);
                Uploads.Add((name, bytes));
                return Json("{\"id\":\"file-" + Uploads.Count + "\",\"filename\":\"" + name + "\",\"bytes\":" + bytes.Length + ",\"created_at\":0,\"object\":\"file\"}");
            }
            if (path.EndsWith("/responses", StringComparison.Ordinal))
            {
                Prompt = await request.Content!.ReadAsStringAsync(token);
                return Json(Responses.TryDequeue(out string? response) ? response : "{\"id\":\"response-one\",\"status\":\"completed\",\"output\":[{\"type\":\"message\",\"role\":\"assistant\",\"content\":[{\"type\":\"output_text\",\"text\":\"done\"}]}]}");
            }
            throw new InvalidOperationException("Unexpected endpoint: " + path);
        }
        private static HttpResponseMessage Json(string json) => new(HttpStatusCode.OK) { Content = new StringContent(json, Encoding.UTF8, "application/json") };
    }
}

internal sealed class ControlledSessionResources : IInferenceResourceAccess, IDisposable
{
    private readonly object _gate = new();
    private readonly Dictionary<InferenceResourceReference, (InferenceResourceDescriptor Descriptor, byte[] Bytes)> _content = [];
    private readonly List<InferenceResourceReference> _selected = [];
    private long _revision;
    private int _next;
    public string WorkspaceId => "workspace";
    public string SessionId => "logical-session";
    internal int SelectionReads { get; private set; }
    internal int OpenedReads { get; private set; }
    internal int DisposedReads { get; private set; }
    internal int DisposeCalls { get; private set; }
    internal Func<CancellationToken, Task>? BeforeSelection { get; set; }
    internal Func<CancellationToken, Task>? BeforeRead { get; set; }

    internal async Task<InferenceResourceReference> RegisterAsync(string name, string type, string content)
    {
        byte[] bytes = Encoding.UTF8.GetBytes(content);
        await using IInferenceResourceWriteHandle handle = await OpenWriteAsync(new(SessionId, name, type, bytes.Length));
        await handle.Content.WriteAsync(bytes);
        return (await handle.CommitAsync(bytes.Length, new() { SelectForSession = true })).Resource.Reference;
    }

    public Task<InferenceResourceDescriptor?> GetAsync(InferenceResourceReference reference, CancellationToken cancellationToken = default)
    { lock (_gate) return Task.FromResult(_content.TryGetValue(reference, out var value) ? value.Descriptor : null); }
    public Task<IInferenceResourceReadHandle> OpenReadAsync(InferenceResourceReference reference, CancellationToken cancellationToken = default)
    {
        lock (_gate)
        {
            var value = _content[reference]; OpenedReads++;
            return Task.FromResult<IInferenceResourceReadHandle>(new ReadHandle(value.Descriptor, value.Bytes, () => DisposedReads++, BeforeRead));
        }
    }
    public Task<IInferenceResourceWriteHandle> OpenWriteAsync(InferenceResourceCreate resource, CancellationToken cancellationToken = default)
    { lock (_gate) return Task.FromResult<IInferenceResourceWriteHandle>(new WriteHandle(this, new(WorkspaceId, "resource-" + ++_next), resource)); }
    public async Task<InferenceResourceSelection> GetSelectionAsync(CancellationToken cancellationToken = default)
    {
        if (BeforeSelection is { } before) await before(cancellationToken);
        lock (_gate) { SelectionReads++; return Selection(); }
    }
    public Task<InferenceResourceSelection> SelectAsync(IReadOnlyList<InferenceResourceReference> references, CancellationToken cancellationToken = default)
    {
        lock (_gate)
        {
            foreach (var reference in references) if (!_content.ContainsKey(reference)) throw new InvalidOperationException("Missing committed content.");
            bool changed = false;
            foreach (var reference in references) if (!_selected.Contains(reference)) { _selected.Add(reference); changed = true; }
            if (changed) _revision++;
            return Task.FromResult(Selection());
        }
    }
    public Task<InferenceResourceSelection> ReplaceSelectionAsync(IReadOnlyList<InferenceResourceReference> references, long expectedRevision, CancellationToken cancellationToken = default)
    {
        lock (_gate)
        {
            if (expectedRevision != _revision) throw new InferenceResourceSelectionConflictException(expectedRevision, _revision);
            foreach (var reference in references) if (!_content.ContainsKey(reference)) throw new InvalidOperationException("Missing committed content.");
            if (!_selected.SequenceEqual(references)) { _selected.Clear(); _selected.AddRange(references); _revision++; }
            return Task.FromResult(Selection());
        }
    }
    private InferenceResourceSelection Selection() => new(WorkspaceId, SessionId, _revision, _selected);
    public void Dispose() => DisposeCalls++;
    private sealed class ReadHandle(InferenceResourceDescriptor descriptor, byte[] bytes, Action disposed,
        Func<CancellationToken, Task>? beforeRead) : IInferenceResourceReadHandle
    {
        public InferenceResourceDescriptor Resource => descriptor;
        public Stream Content { get; } = beforeRead is null ? new MemoryStream(bytes, writable: false) : new HeldReadStream(bytes, beforeRead);
        public ValueTask DisposeAsync() { Content.Dispose(); disposed(); return ValueTask.CompletedTask; }
    }
    private sealed class HeldReadStream(byte[] bytes, Func<CancellationToken, Task> beforeRead) : MemoryStream(bytes, writable: false)
    {
        public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        { await beforeRead(cancellationToken); return Read(buffer.Span); }
    }
    private sealed class WriteHandle(ControlledSessionResources owner, InferenceResourceReference reference, InferenceResourceCreate create) : IInferenceResourceWriteHandle
    {
        public InferenceResourceReference Reference => reference;
        public Stream Content { get; } = new MemoryStream();
        public Task<InferenceResourceCommitResult> CommitAsync(long bytesWritten, InferenceResourceCommitOptions? options = null, CancellationToken cancellationToken = default)
        {
            lock (owner._gate)
            {
                byte[] bytes = ((MemoryStream)Content).ToArray();
                if (bytesWritten != bytes.Length || create.ExpectedBytes is { } expected && expected != bytes.Length) throw new InvalidOperationException("Incomplete content.");
                var descriptor = new InferenceResourceDescriptor(reference, create.SessionId, create.FileName, create.ContentType, bytes.Length);
                owner._content.Add(reference, (descriptor, bytes));
                InferenceResourceSelection? selection = null;
                if (options?.SelectForSession == true) { owner._selected.Add(reference); owner._revision++; selection = owner.Selection(); }
                return Task.FromResult(new InferenceResourceCommitResult(descriptor, selection));
            }
        }
        public ValueTask DisposeAsync() { Content.Dispose(); return ValueTask.CompletedTask; }
    }
}
